<script setup lang="ts">
import type { HTMLAttributes } from 'vue'
import katex from 'katex'
import { computed } from 'vue'
import 'katex/dist/katex.min.css'

defineOptions({ inheritAttrs: false })

const props = defineProps<{
  content: string
  class?: HTMLAttributes['class']
}>()

const isBlock = computed(() => props.class?.toString().split(/\s+/).includes('block') ?? false)

const rendered = computed(() => {
  try {
    return katex.renderToString(props.content, {
      displayMode: isBlock.value,
      output: 'htmlAndMathml',
      throwOnError: true,
      trust: false,
      maxExpand: 1000,
      maxSize: 10,
    })
  } catch {
    return null
  }
})
</script>

<template>
  <div v-if="isBlock" class="math block my-3 min-w-0 max-w-full overflow-x-auto py-1" data-ai-markdown-math>
    <!-- eslint-disable-next-line vue/no-v-html -- content is generated by KaTeX with trust=false -->
    <span v-if="rendered" v-html="rendered" />
    <code v-else class="whitespace-pre-wrap break-words text-xs text-qt-muted">{{ props.content }}</code>
  </div>
  <span v-else class="math inline align-middle" data-ai-markdown-math>
    <!-- eslint-disable-next-line vue/no-v-html -- content is generated by KaTeX with trust=false -->
    <span v-if="rendered" v-html="rendered" />
    <code v-else class="text-xs text-qt-muted">{{ props.content }}</code>
  </span>
</template>
